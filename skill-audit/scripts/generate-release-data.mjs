#!/usr/bin/env node

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const packagePath = join(packageRoot, "package.json");
const rulesPath = join(packageRoot, "rules", "default-patterns.json");
const outputPath = join(packageRoot, "src", "generated", "release-data.ts");

const packageJson = JSON.parse(readFileSync(packagePath, "utf8"));
const rulesBytes = readFileSync(rulesPath);
const rules = JSON.parse(rulesBytes.toString("utf8"));
const rulesSha256 = createHash("sha256").update(rulesBytes).digest("hex");
const generated = await format(
  `// Generated by scripts/generate-release-data.mjs. Do not edit.\n` +
    `export const PACKAGE_VERSION = ${JSON.stringify(packageJson.version)};\n` +
    `export const EMBEDDED_RULES_SHA256 = ${JSON.stringify(rulesSha256)};\n` +
    `export const EMBEDDED_DEFAULT_PATTERNS = ${JSON.stringify(rules)} as const;\n`,
  { parser: "typescript" },
);

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outputPath, "utf8");
  } catch {
    // The mismatch below provides the actionable error.
  }
  if (current !== generated) {
    throw new Error(
      "Generated release data is stale; run npm run generate:release-data",
    );
  }
} else {
  writeFileSync(outputPath, generated);
}
